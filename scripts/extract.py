def count_signals(pages, signals):
    total, hit = 0, 0
    low_pages = [p.lower() for p in pages]
    for s in signals:
        sl = s.lower()
        hits = 0
        for p in low_pages:
            hits += p.count(sl)
        total += hits
        if hits:
            hit += 1
    return total, hit


