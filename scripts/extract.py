    idx = text.find(term)
    tries = 0
    while idx != -1 and tries < 400:
        left = max(text.rfind(p, 0, idx) + 1 for p in "。！？；\n")
        right = text.find("。", idx)
        if right == -1:
            right = len(text)
        for pat in ("；", "！", "？", "\n"):
            r2 = text.find(pat, idx)
            if r2 != -1:
                right = min(right, r2)
        right = min(right, idx + max_len)
        frag = re.sub(r"\s+", "", text[left:right + 1])
        if min_len <= len(frag) <= max_len + 4:
            return frag
        idx = text.find(term, idx + 1)
        tries += 1
    return ""


