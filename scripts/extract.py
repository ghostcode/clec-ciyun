def extract_phrases(text, topn=140, min_count=10):
    """自研中文短语发现：
    1) 滑窗生成 2~7 字 CJK n-gram，边界虚词过滤
    2) 按长度从长到短处理，用「残量」剔除被更长词吞掉的碎片
    3) 按 score = 残量 × 长度^1.7 排序取前 topn，再过通用词黑名单
    """
    counts = Counter()
    for seg in re.findall(rf"[{CJK}]+", text):
        n = len(seg)
        if n < 2:
            continue
        for L in (2, 3, 4, 5, 6, 7):
            for i in range(n - L + 1):
                g = seg[i:i + L]
                if g[0] in EDGE_STOP or g[-1] in EDGE_STOP:
                    continue
                if len(set(g)) == 1:
                    continue
                counts[g] += 1

    cands = [g for g, c in counts.items() if c >= min_count and g not in GENERIC_STOP]
    if not cands:
        return []
    # 长词优先，让「斯达克」「金流」这类碎片被「纳斯达克」「现金流」吞掉
    cands.sort(key=lambda g: (-len(g), -counts[g]))

    # 建立「直接上层词」索引：h 是 g 的直接延展 <=> g 是 h 去掉首字或尾字
    supers = defaultdict(list)
    cand_set = set(cands)
    for h in cands:
        if len(h) >= 3:
            if h[:-1] in cand_set:
                supers[h[:-1]].append(h)
            if h[1:] in cand_set:
                supers[h[1:]].append(h)

    # 「被更长词吞掉」的次数（与处理顺序无关，天然支持多层嵌套：
    #   达克 <- 斯达克 <- 纳斯达克）
    kept = {}
    for g in cands:
        covered = min(counts[g], sum(counts[h] for h in supers.get(g, ())))
        resid = counts[g] - covered
        if resid >= max(8, counts[g] * 0.35):
            kept[g] = resid

    def score(g):
        return kept[g] * (len(g) ** 1.7)

    ranked = sorted(kept, key=score, reverse=True)
    out = []
    for g in ranked:
        if g in GENERIC_STOP:
            continue
        out.append((g, int(kept[g]), counts[g]))
        if len(out) >= topn:
            break
    return out


